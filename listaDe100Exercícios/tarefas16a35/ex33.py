print("=== Exercício 33: Dia da Semana ===")
n = int(input("Digite um número de 1 a 7: "))
if n == 1:
    print("SEGUNDA-FEIRA")
elif n == 2:
    print("TERÇA-FEIRA")
elif n == 3:
    print("QUARTA-FEIRA")
elif n == 4:
    print("QUINTA-FEIRA")
elif n == 5:
    print("SEXTA-FEIRA")
elif n == 6:
    print("SÁBADO")
elif n == 7:
    print("DOMINGO")
else:
    print("OPÇÃO INVÁLIDA")